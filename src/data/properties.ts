/* —— Builders ——————————————————————————————————————————————————————————— */

/** Photos for a listing come from the generated manifest (see scripts/fetch-photos.mjs),
 *  so the gallery labels always match the files on disk. */
function photos(id: string, subject: string): PropertyPhoto[] {
  const listed = photoManifest[id];
  if (listed && listed.length) {
    return listed.map((p) => ({ src: p.src, alt: p.alt, room: p.room }));
  }
  return [1, 2, 3, 4, 5].map((n) => ({
    src: `/photos/${id}/${String(n).padStart(2, "0")}.jpg`,
    alt: `${subject} - photo ${n} of 5`,
    room: "Photo",
  }));
}

function landlord() {
  return {
    name: site.landlord.name,
    phone: site.landlord.phone,
    whatsapp: site.whatsappNumber,
    verified: site.landlord.verified,
    responseTime: site.landlord.responseTime,
    license: site.landlord.license,
  };
}

type Seed = Omit<Property, "photos" | "landlord" | "location"> & {
  lat: number;
  lng: number;
};

function build(seed: Seed): Property {
  const { lat, lng, ...rest } = seed;
  return {
    ...rest,
    photos: photos(seed.id, seed.title),
    landlord: landlord(),
    location: { lat, lng },
  };
}

